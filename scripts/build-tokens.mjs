#!/usr/bin/env node
/**
 * Generates design tokens from the design file (Pencil .pen).
 *
 *   node scripts/build-tokens.mjs           write src/tokens/*
 *   node scripts/build-tokens.mjs --check   exit 1 if src/tokens/* is out of date
 *
 * Source: the path in VIA_PEN_FILE or .design-file (see scripts/pen-file.mjs). Pencil stores
 * variables as JSON: { type, value } where value is a literal, a "$alias", or a
 * list of { value, theme: { mode } } entries.
 *
 * Rules:
 * - via.a.b → --via-a-b
 * - Light values on :root, dark overrides on [data-theme="dark"]
 * - Aliases are written as resolved values in both blocks, never var() chains
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { penFilePath } from './pen-file.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const penFile = penFilePath(root);
if (!penFile || !existsSync(penFile)) {
  console.error('No design file: set VIA_PEN_FILE or write its path in .design-file (see scripts/pen-file.mjs).');
  process.exit(2);
}
const outDir = path.join(root, 'src/tokens');
const THEMES = ['light', 'dark'];

const doc = JSON.parse(readFileSync(penFile, 'utf8'));
const variables = doc.variables ?? {};

// ---------------------------------------------------------------- resolve

function pick(def, theme) {
  const v = def.value;
  if (!Array.isArray(v)) return v;
  const match = v.find((e) => e.theme?.mode === theme) ?? v.find((e) => !e.theme) ?? v[0];
  return match.value;
}

function resolve(name, theme, seen = []) {
  const def = variables[name];
  if (!def) throw new Error(`Unknown token "${name}" (referenced by ${seen.at(-1) ?? 'root'})`);
  if (seen.includes(name)) throw new Error(`Alias cycle: ${[...seen, name].join(' → ')}`);
  const v = pick(def, theme);
  if (typeof v === 'string' && v.startsWith('$')) return resolve(v.slice(1), theme, [...seen, name]);
  return v;
}

// ---------------------------------------------------------------- format

const cssVar = (name) => `--${name.replace(/\./g, '-')}`;

const UNITLESS = [/^via\.layer\./, /^via\.type\..*-line$/];
const MS = [/^via\.motion\./];

function formatNumber(name, n) {
  if (UNITLESS.some((r) => r.test(name))) return String(n);
  if (MS.some((r) => r.test(name))) return `${n}ms`;
  return n === 0 ? '0' : `${n}px`;
}

const quote = (family) => (/[\s]/.test(family) ? `'${family}'` : family);

function formatString(name, s, theme) {
  if (!name.startsWith('via.font.') || name.startsWith('via.font.fallback')) return s;
  const fallback =
    name === 'via.font.display'
      ? resolve('via.font.fallback-serif', theme)
      : name === 'via.font.mono'
        ? 'ui-monospace, monospace'
        : resolve('via.font.fallback', theme);
  return `${quote(s)}, ${fallback}`;
}

function formatColor(c) {
  return String(c).toLowerCase();
}

function format(name, type, value, theme) {
  if (type === 'number') return formatNumber(name, value);
  if (type === 'string') return formatString(name, value, theme);
  if (type === 'color') return formatColor(value);
  if (type === 'boolean') return value ? '1' : '0';
  throw new Error(`Unsupported type ${type} for ${name}`);
}

// ---------------------------------------------------------------- build

const names = Object.keys(variables).sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));

const tokens = {};
for (const name of names) {
  const def = variables[name];
  const raw = {};
  const css = {};
  for (const theme of THEMES) {
    raw[theme] = resolve(name, theme);
    css[theme] = format(name, def.type, raw[theme], theme);
  }
  const source = def.value;
  tokens[name] = {
    type: def.type,
    cssVar: cssVar(name),
    themed: css.light !== css.dark,
    alias: Array.isArray(source)
      ? source.map((e) => (typeof e.value === 'string' && e.value.startsWith('$') ? e.value.slice(1) : null))
          .find(Boolean) ?? null
      : typeof source === 'string' && source.startsWith('$')
        ? source.slice(1)
        : null,
    value: raw,
    css,
  };
}

const sourceHash = createHash('sha256').update(JSON.stringify(variables)).digest('hex').slice(0, 12);
const header = `Generated by scripts/build-tokens.mjs from the design file (variables ${sourceHash}). Do not edit; run \`npm run tokens\`.`;

const cssOut = [
  `/* ${header} */`,
  '',
  ':root {',
  ...names.map((n) => `  ${tokens[n].cssVar}: ${tokens[n].css.light};`),
  '}',
  '',
  ':root[data-theme="dark"],',
  '[data-theme="dark"] {',
  ...names.filter((n) => tokens[n].themed).map((n) => `  ${tokens[n].cssVar}: ${tokens[n].css.dark};`),
  '}',
  '',
].join('\n');

const jsonOut = JSON.stringify({ $comment: header, source: { variables: sourceHash }, tokens }, null, 2) + '\n';

const numberTokens = (prefix) =>
  Object.fromEntries(names.filter((n) => n.startsWith(prefix)).map((n) => [n.slice(prefix.length), tokens[n].value.light]));

const tsOut = `// ${header}

/** Every token name in the design file. */
export type TokenName =
${names.map((n) => `  | '${n}'`).join('\n')};

/** CSS custom property reference for a token, e.g. token('via.semantic.text.primary') → 'var(--via-semantic-text-primary)'. */
export function token(name: TokenName): string {
  return \`var(--\${name.replace(/\\./g, '-')})\`;
}

/** Breakpoints in px. CSS media queries can't read custom properties, so use these in JS. */
export const breakpoints = ${JSON.stringify(numberTokens('via.breakpoint.'), null, 2)} as const;

/** z-index scale. */
export const layers = ${JSON.stringify(numberTokens('via.layer.'), null, 2)} as const;

/** Motion durations in ms. */
export const durations = ${JSON.stringify(
  Object.fromEntries(names.filter((n) => n.startsWith('via.motion.') && tokens[n].type === 'number').map((n) => [n.slice(11), tokens[n].value.light])),
  null,
  2,
)} as const;
`;

const outputs = {
  'tokens.css': cssOut,
  'tokens.json': jsonOut,
  'tokens.ts': tsOut,
};

if (process.argv.includes('--check')) {
  const stale = Object.entries(outputs).filter(([file, content]) => {
    const p = path.join(outDir, file);
    return !existsSync(p) || readFileSync(p, 'utf8') !== content;
  });
  if (stale.length) {
    console.error(`Tokens are out of date with ${path.relative(root, penFile)}: ${stale.map(([f]) => f).join(', ')}. Run \`npm run tokens\`.`);
    process.exit(1);
  }
  console.log(`Tokens up to date (${names.length} tokens, variables ${sourceHash}).`);
} else {
  mkdirSync(outDir, { recursive: true });
  for (const [file, content] of Object.entries(outputs)) writeFileSync(path.join(outDir, file), content);
  console.log(`Wrote ${Object.keys(outputs).length} files to src/tokens (${names.length} tokens, ${names.filter((n) => tokens[n].themed).length} themed).`);
}
